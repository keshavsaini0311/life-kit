from datetime import date, datetime, timedelta, timezone
import json
from pathlib import Path
import tempfile
import unittest

from lifekit import core, ledger, learning, maintain

HDFC_STYLE = """Date,Narration,Chq./Ref.No.,Value Dt,Withdrawal Amt.,Deposit Amt.,Closing Balance
01/10/26,UPI-SWIGGY-ORDER,R1,01/10/26,"1,250.50",,"10,000.00"
02/10/26,UPI-TO SELF SAVINGS,R2,02/10/26,5000.00,,5000.00
03/10/26,SALARY OCT,R3,03/10/26,,90000.00,95000.00
04/10/26,UNKNOWN SHOP,R4,04/10/26,99.00,,94901.00
"""
GENERIC = """Txn Date,Description,Debit,Credit,Balance
2026-10-05,Zomato order,450,,1000
2026-10-05,Zomato order,450,,550
"""


class LedgerTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = core.init(Path(self.temp.name) / "w", "INR")
        (self.root / "finance/inbox").mkdir(parents=True)
        self.rules([{"match": "swiggy", "category": "food"}, {"match": "zomato", "category": "food"},
                    {"match": "to self", "kind": "transfer"}])

    def rules(self, rules):
        (self.root / "finance/rules.json").write_text(json.dumps(rules))

    def drop(self, name, text):
        (self.root / "finance/inbox" / name).write_text(text)

    def spends(self):
        return [e for e in core.events(self.root) if e["kind"] == "spend"]

    def test_parse_common_bank_headers(self):
        self.drop("a.csv", HDFC_STYLE)
        rows, errors = ledger.parse_csv(self.root / "finance/inbox/a.csv")
        self.assertEqual(errors, [])
        self.assertEqual(rows[0]["date"], "2026-10-01")
        self.assertEqual(str(rows[0]["debit"]), "1250.50")
        self.assertIsNone(rows[2]["debit"])
        self.assertEqual(str(rows[2]["credit"]), "90000.00")
        self.drop("b.csv", GENERIC)
        rows, errors = ledger.parse_csv(self.root / "finance/inbox/b.csv")
        self.assertEqual((rows[0]["date"], str(rows[0]["debit"])), ("2026-10-05", "450"))

    def test_identical_purchases_in_one_export_both_post(self):
        self.drop("b.csv", GENERIC)
        result = ledger.import_inbox(self.root)
        self.assertEqual(result["posted"], 2)
        self.assertEqual(len(self.spends()), 2)

    def test_overlapping_exports_dedupe(self):
        self.drop("b.csv", GENERIC)
        ledger.import_inbox(self.root)
        self.drop("b2.csv", GENERIC + "2026-10-06,Zomato order,200,,350\n")
        result = ledger.import_inbox(self.root)
        self.assertEqual(result["posted"], 1)
        self.assertEqual(len(self.spends()), 3)

    def test_bank_spend_is_observed_with_transaction_date(self):
        self.drop("a.csv", HDFC_STYLE)
        ledger.import_inbox(self.root)
        swiggy = self.spends()[0]
        self.assertEqual((swiggy["source"], swiggy["on"], swiggy["amount"], swiggy["category"]),
                         ("bank-csv", "2026-10-01", "1250.50", "food"))

    def test_transfer_rule_not_spend(self):
        self.drop("a.csv", HDFC_STYLE)
        ledger.import_inbox(self.root)
        self.assertNotIn("5000.00", [e["amount"] for e in self.spends()])

    def test_credit_never_spend(self):
        self.drop("a.csv", HDFC_STYLE)
        ledger.import_inbox(self.root)
        self.assertNotIn("90000.00", [e["amount"] for e in self.spends()])

    def test_unmatched_goes_to_review(self):
        self.drop("a.csv", HDFC_STYLE)
        result = ledger.import_inbox(self.root)
        self.assertEqual(result["review"], 1)
        self.assertIn("UNKNOWN SHOP", (self.root / "finance/imports/review.md").read_text())
        self.assertNotIn("99.00", [e["amount"] for e in self.spends()])

    def test_rule_added_then_rerun_posts(self):
        self.drop("a.csv", HDFC_STYLE)
        ledger.import_inbox(self.root)
        self.rules([{"match": "swiggy", "category": "food"}, {"match": "to self", "kind": "transfer"},
                    {"match": "unknown shop", "category": "shopping"}])
        result = ledger.import_inbox(self.root)
        self.assertEqual(result["posted"], 1)
        self.assertEqual(sorted(e["amount"] for e in self.spends()), ["1250.50", "99.00"])
        self.assertNotIn("UNKNOWN SHOP", (self.root / "finance/imports/review.md").read_text())

    def test_bad_date_row_reported_file_kept(self):
        self.drop("bad.csv", GENERIC + "yesterday,Zomato order,10,,1\n")
        result = ledger.import_inbox(self.root)
        self.assertTrue(result["errors"])
        self.assertTrue((self.root / "finance/inbox/bad.csv").exists())
        self.assertEqual(self.spends(), [])

    def test_ledger_unknown_not_zero(self):
        text = ledger.render(self.root, "2026-09").read_text()
        self.assertIn("unknown, not zero", text)
        self.assertIn("generated by life-kit", text)

    def test_ledger_lists_days_and_totals(self):
        self.drop("a.csv", HDFC_STYLE)
        ledger.import_inbox(self.root)
        text = ledger.render(self.root, "2026-10").read_text()
        self.assertIn("2026-10-01", text)
        self.assertIn("INR 1250.50", text)
        self.assertIn("1 bank row awaiting a rule", text)

    def test_ledger_multi_currency_not_summed(self):
        core.spend(self.root, "10.00", "food", on=date.today().isoformat())
        core.update_config(self.root, lambda c: c.update(currency="USD"))
        core.spend(self.root, "2.00", "food", on=date.today().isoformat())
        text = ledger.render(self.root, date.today().strftime("%Y-%m")).read_text()
        self.assertIn("INR 10.00", text)
        self.assertIn("USD 2.00", text)
        self.assertNotIn("12.00", text)

    def test_bad_encoding_file_reported_and_other_rows_kept(self):
        self.drop("a.csv", HDFC_STYLE)
        (self.root / "finance/inbox/b.csv").write_bytes("Date,Narration,Withdrawal,Deposit\n01/10/26,Caf\xe9,10,\n".encode("latin-1"))
        result = ledger.import_inbox(self.root)
        self.assertTrue(any("b.csv" in e for e in result["errors"]))
        self.assertTrue((self.root / "finance/inbox/b.csv").exists())
        self.assertIn("UNKNOWN SHOP", (self.root / "finance/imports/review.md").read_text())
        self.assertEqual(len(self.spends()), 1)


def event(kind, days_ago, **fields):
    at = (datetime.now(timezone.utc) - timedelta(days=days_ago)).isoformat()
    row = {"schema_version": 1, "source": "user-reported", "kind": kind, "at": at, "id": fields.pop("id")}
    row.update(fields)
    return row


class LearningTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = core.init(Path(self.temp.name) / "w", "INR")

    def write(self, rows):
        path = self.root / "learning/events.jsonl"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("".join(json.dumps(r) + "\n" for r in rows))

    def actions(self, n, days_ago, channel="email", variant="a", start=0):
        return [event("action", days_ago, id="act" + str(start + i), domain="learning", channel=channel,
                      target="t" + str(start + i), variant=variant) for i in range(n)]

    def test_learning_rate_needs_five_eligible(self):
        rows = self.actions(4, 20)
        rows.append(event("outcome", 10, id="o1", domain="learning", action_id="act0", stage="completed", evidence="self-report"))
        self.write(rows)
        text = learning.report(self.root).read_text()
        self.assertIn("too few", text)
        self.assertNotIn("25%", text)

    def test_rate_shown_with_five_eligible(self):
        rows = self.actions(5, 20)
        rows += [event("outcome", 10, id="o1", domain="learning", action_id="act0", stage="completed", evidence="x"),
                 event("outcome", 9, id="o2", domain="learning", action_id="act0", stage="completed", evidence="dup")]
        self.write(rows)
        self.assertIn("completed 1/5 (20%)", learning.report(self.root).read_text())

    def test_recent_actions_excluded_from_rates(self):
        self.write(self.actions(5, 20) + self.actions(5, 2, start=5))
        text = learning.report(self.root).read_text()
        self.assertIn("completed 0/5 (0%)", text)
        self.assertIn("5 too recent", text)

    def test_followups_listed_after_14_days(self):
        self.write(self.actions(1, 20) + self.actions(1, 3, start=1))
        text = learning.report(self.root).read_text()
        self.assertIn("act0", text.split("## Activities to review")[1])
        self.assertNotIn("act1", text.split("## Activities to review")[1])

    def test_maintain_writes_freshness(self):
        path = maintain.run(self.root)
        text = path.read_text()
        self.assertTrue(path.name.startswith("maintenance-"))
        self.assertIn("No check-in", text)
        self.assertIn("Spending this month: unknown", text)


if __name__ == "__main__":
    unittest.main()
